import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {lessons,stages,cases,questions,educationSources,exampleRatio,scoreAnswers} from './dist/education.mjs';
import {sources} from './dist/sources.mjs';
import {cropProfiles} from './dist/flower.mjs';
import {additionalCrops} from './dist/catalog.mjs';
const allSources=[...educationSources,...sources],ids=new Set(allSources.map(s=>s.id));
assert.equal(ids.size,allSources.length,'source identifiers must be unique');
for(const section of [...lessons,...stages,...cases])for(const id of section.refs)assert.ok(ids.has(id),'unresolved source '+id);
assert.equal(lessons.length,6);assert.equal(stages.length,6);assert.equal(questions.length,6);
for(const q of [...questions,...cases])assert.ok(Number.isInteger(q.answer)&&q.answer>=0&&q.answer<q.options.length);
assert.equal(scoreAnswers(questions.map(()=>null)),0);
assert.equal(scoreAnswers(questions.map(q=>q.answer)),6);
assert.equal(scoreAnswers(questions.map(q=>(q.answer+1)%q.options.length)),0);
assert.equal(exampleRatio(40,2),20);assert.equal(exampleRatio(30,1.5),20);assert.equal(exampleRatio(40,1),40);
assert.throws(()=>exampleRatio(40,0));assert.throws(()=>exampleRatio(99,2));
const html=readFileSync('dist/index.html','utf8'),js=readFileSync('dist/app.js','utf8');
const dynamicHtml=readFileSync('dist/guide.mjs','utf8')+readFileSync('dist/durian-guide.mjs','utf8');
const domIds=[...(html+dynamicHtml).matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);domIds.push(...[...dynamicHtml.matchAll(/\.id='([^']+)'/g)].map(m=>m[1]));
const staticIds=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(staticIds.length,new Set(staticIds).size,'duplicate static HTML ids');
for(const [,id] of js.matchAll(/\$\('([^']+)'\)/g))assert.ok(domIds.includes(id),'missing DOM target '+id);
for(const l of lessons)assert.ok(html.includes('id="page-'+l.page+'"'));
assert.ok(!/type="(?:number|file)"/.test(html),'education must not require lab / farm data');
assert.ok(!/Ganick|讲座|lecture/i.test(html+js+JSON.stringify(lessons)));
const catalog={...cropProfiles,...additionalCrops};delete catalog.other;assert.equal(Object.keys(catalog).length,14);
for(const crop of Object.values(catalog))for(const id of crop.refs)assert.ok(ids.has(id));
console.log('Passed: six lessons / stages / quiz items, source integrity, 14 crops, quiz scoring, ratio examples, DOM targets, no diagnostic data inputs.');
